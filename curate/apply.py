#!/usr/bin/env python
"""Turns review decisions into the two files the app ships.

    python curate/apply.py            # write public/approved.json and public/blocklist.json
    python curate/apply.py --dry-run  # just report

public/approved.json is the allowlist, and since 2026-10-16 it is the model:
Openverse, Wikimedia Commons and NASA download ONLY the images listed in it,
straight from their original hosts. Each entry is a complete ImageRecord taken
from candidates.jsonl, which harvest.mjs built with the app's own toRecord(),
so it is exactly what the app would have built from a live search. Nothing
unreviewed reaches a device, including whatever the sources add after the
harvest.

public/blocklist.json still matters for two reasons. The Settings "jailbreak"
switch goes back to live searching, and the blocklist is what keeps your
rejections out of that. And reconcileBundledBlocklist() deletes rejected
images that a device downloaded before you rejected them.

The app reads the bundled copy of approved.json and also fetches the deployed
one from GitHub Pages, keeping whichever has the later `generated`. So the round
trip for an existing install is just:

    review  ->  apply.py  ->  commit + push  ->  Pages deploys  ->  devices pick it up

A new APK (npm run cap:sync) is only needed to change what a fresh install
ships with, and for the blocklist, which is only read from the bundle.
"""
import argparse
import json
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
DECISIONS = HERE / "decisions.jsonl"
CANDIDATES = HERE / "candidates.jsonl"
PUBLIC = HERE.parent / "public"
BLOCKLIST = PUBLIC / "blocklist.json"
APPROVED = PUBLIC / "approved.json"

NOTE = "Generated by curate/apply.py from curate/decisions.jsonl. Do not edit by hand."


def load_jsonl(path):
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    if not DECISIONS.exists():
        raise SystemExit(f"no {DECISIONS} — run `python curate/review.py` first")
    if not CANDIDATES.exists():
        raise SystemExit(f"no {CANDIDATES} — approved.json is built from it; run `node curate/harvest.mjs`")

    # Last decision per URL wins. Changing your mind in the reviewer appends a
    # second line for the same image rather than editing the first, so order
    # matters and the tail is the truth.
    latest = {d["url"]: d for d in load_jsonl(DECISIONS) if "url" in d}

    rejected = sorted(u for u, d in latest.items() if d.get("decision") == "reject")
    kept = {u for u, d in latest.items() if d.get("decision") == "keep"}

    # source -> subject -> [ImageRecord]. Keyed by the raw subject value rather
    # than the app's catId(), so the encoding stays in one place: library.js.
    approved = defaultdict(lambda: defaultdict(list))
    found = set()
    for c in load_jsonl(CANDIDATES):
        if c["url"] not in kept or c["url"] in found:
            continue
        found.add(c["url"])
        source, _, subject = c.get("cat", "").partition("::")
        approved[source][subject].append({
            "title": c.get("title") or "Untitled",
            "artist": c.get("artist", ""),
            "date": c.get("date", ""),
            "department": c.get("department", ""),
            "image": c["url"],
            "source": c.get("source") or source,
            "attribution": c.get("attribution", ""),
        })
    for subjects in approved.values():
        for records in subjects.values():
            records.sort(key=lambda r: r["image"])   # stable diffs between runs

    print(f"{len(latest):,} decisions: {len(kept):,} approved, {len(rejected):,} rejected")
    for source in sorted(approved):
        n = sum(len(r) for r in approved[source].values())
        r = sum(1 for d in latest.values() if d.get("decision") == "reject" and d.get("source") == source)
        print(f"  {source:<10} {n:>6,} approved  {r:>6,} rejected")
    lost = kept - found
    if lost:
        print(f"  {len(lost):,} approved image(s) are no longer in candidates.jsonl and were left out")

    if args.dry_run:
        print("\n--dry-run: nothing written")
        return

    generated = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    APPROVED.write_text(json.dumps({
        "version": 1,
        "generated": generated,
        "note": NOTE,
        "sources": {s: dict(sorted(subj.items())) for s, subj in sorted(approved.items())},
    }, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    BLOCKLIST.write_text(json.dumps({
        "version": 1,
        "generated": generated,
        "note": NOTE,
        "blocked": rejected,
    }, indent=2) + "\n", encoding="utf-8")

    size = APPROVED.stat().st_size / 1024
    print(f"\nwrote {APPROVED.relative_to(HERE.parent)} ({len(found):,} images, {size:,.0f} KB)")
    print(f"wrote {BLOCKLIST.relative_to(HERE.parent)} ({len(rejected):,} blocked URLs)")
    print("next: commit and push, and Pages delivers approved.json to every device")


if __name__ == "__main__":
    main()
